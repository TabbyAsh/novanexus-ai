#!/usr/bin/env python3
"""Build the extension download from tracked source. No dependencies or secrets."""
from pathlib import Path
import subprocess, tempfile, zipfile, io, base64, hashlib
root=Path(__file__).resolve().parent.parent
with tempfile.TemporaryDirectory(prefix='nova-lens-') as tmp:
    folder=Path(tmp)/'Nova-Lens'
    subprocess.run(['node',str(root/'scripts/build-nova-lens-extension.mjs'),str(folder)],check=True)
    buffer=io.BytesIO()
    with zipfile.ZipFile(buffer,'w',compression=zipfile.ZIP_DEFLATED,compresslevel=9) as archive:
        for path in sorted(folder.rglob('*')):
            if not path.is_file(): continue
            info=zipfile.ZipInfo('Nova-Lens/'+path.relative_to(folder).as_posix(),date_time=(2026,10,26,0,0,0))
            info.compress_type=zipfile.ZIP_DEFLATED
            info.external_attr=0o100644<<16
            archive.writestr(info,path.read_bytes())
    data=buffer.getvalue()
    target=root/'apps/web/src/lib/world/lens-package.server.ts'
    target.write_text("// Generated by scripts/package-nova-lens-download.py; extension code only.\nimport 'server-only';\nexport const lensSha256 = '"+hashlib.sha256(data).hexdigest()+"';\nexport const lensZip = '"+base64.b64encode(data).decode()+"';\n")
    print(f'Packaged {len(data)} bytes; SHA256 {hashlib.sha256(data).hexdigest()}')
